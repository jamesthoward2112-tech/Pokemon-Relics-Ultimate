u32 GiveScriptedMonToPlayer(struct Pokemon *mon, u8 slot)
{
    u32 sentToPc;
    u32 i = 0;
    if (slot < PARTY_SIZE)
    {
        CopyMon(&gPlayerParty[slot], mon, sizeof(struct Pokemon));
        sentToPc = MON_GIVEN_TO_PARTY;
    }
    else
    {
        for (i = 0; i < GetMaxPartySize(); i++) // tx_randomizer_and_challenges: party limit
        {
            if (GetMonData(&gPlayerParty[i], MON_DATA_SPECIES) == SPECIES_NONE)
                break;
        }
        if (i >= GetMaxPartySize())
        {
            sentToPc = CopyMonToPC(mon);
        }
        else
        {
            if (!DoesSpeciesPassOneTypeChallenge(GetMonData(mon, MON_DATA_SPECIES)))
            {
                sentToPc = CopyMonToPC(mon);
            }
            else
            {
                sentToPc = MON_GIVEN_TO_PARTY;
                CopyMon(&gPlayerParty[i], mon, sizeof(struct Pokemon));
                gPlayerPartyCount = i + 1;
            }
        }
    }
    if (sentToPc != MON_CANT_GIVE)
    {
        HandleSetPokedexFlagFromMon(mon, FLAG_SET_SEEN);
        HandleSetPokedexFlagFromMon(mon, FLAG_SET_CAUGHT);
    }
    return sentToPc;
}

